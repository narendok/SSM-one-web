CREATE TABLE public.customer_requirements(id uuid PRIMARY KEY,requirement_number text NOT NULL UNIQUE,opportunity_id uuid NOT NULL REFERENCES public.sales_opportunities(id),customer_id uuid NOT NULL,title text NOT NULL,status text NOT NULL,current_revision integer NOT NULL);
