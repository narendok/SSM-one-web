CREATE SCHEMA extensions;
CREATE EXTENSION pgcrypto WITH SCHEMA extensions;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
CREATE TABLE public.permission_test_grants(user_id uuid NOT NULL, permission_key text NOT NULL, PRIMARY KEY(user_id,permission_key));
CREATE FUNCTION public.has_permission(p_user uuid,p_key text) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$ SELECT EXISTS(SELECT 1 FROM public.permission_test_grants WHERE user_id=p_user AND permission_key=p_key) $$;
